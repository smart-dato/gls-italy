<?php

namespace SmartDato\GlsItaly\Tracking\Results;

use Carbon\Carbon;
use Exception;
use Saloon\Http\Response;
use SimpleXMLElement;
use SmartDato\GlsItaly\Data\TrackingEventData;

final class PickupTrackingResult
{
    use ParsesTrackingEvents;

    private function __construct(
        private readonly string $url,
        private readonly string $rawResponse,
    ) {}

    public static function fromResponse(Response $response): self
    {
        return new self((string) $response->getPsrRequest()->getUri(), $response->body());
    }

    /**
     * Replay a stored response, e.g. from a tracking log.
     */
    public static function fromStrings(string $rawResponse, string $url = ''): self
    {
        return new self($url, $rawResponse);
    }

    public function hasPickup(): bool
    {
        $xml = $this->xml();

        return $xml !== null && isset($xml->RITIRO);
    }

    /**
     * The TRACKINGRITIRO events of the pickup itself.
     *
     * @return array<int, TrackingEventData>
     */
    public function pickupEvents(): array
    {
        $tracking = $this->xml()?->RITIRO?->TRACKINGRITIRO;

        if ($tracking === null) {
            return [];
        }

        $events = json_decode((string) json_encode($tracking), true, 512, JSON_THROW_ON_ERROR);

        if (! is_array($events) || ! array_key_exists('Codice', $events)) {
            return [];
        }

        if (is_array($events['Codice'])) {
            $returns = [];
            for ($i = 0, $iMax = count($events['Codice']); $i < $iMax; $i++) {
                $returns[] = $this->pickupEvent(
                    (string) ($events['Data'][$i] ?? ''),
                    (string) ($events['Ora'][$i] ?? ''),
                    (string) ($events['Luogo'][$i] ?? ''),
                    (string) ($events['Stato'][$i] ?? ''),
                    (string) $events['Codice'][$i],
                );
            }

            return $returns;
        }

        return [$this->pickupEvent(
            $this->scalar($events, 'Data'),
            $this->scalar($events, 'Ora'),
            $this->scalar($events, 'Luogo'),
            $this->scalar($events, 'Stato'),
            $this->scalar($events, 'Codice'),
        )];
    }

    /**
     * The tracking events of the shipment generated by the pickup.
     *
     * @return array<int, TrackingEventData>
     */
    public function shipmentEvents(): array
    {
        return $this->walkShipmentEvents($this->xml()?->RITIRO);
    }

    public function shipmentNumber(): ?string
    {
        $number = $this->xml()?->RITIRO?->SPEDIZIONE?->NumSped;

        return $number === null ? null : (string) $number;
    }

    public function shipmentDepartureSede(): ?string
    {
        $sede = $this->xml()?->RITIRO?->SPEDIZIONE?->SedePartenza;

        return $sede === null ? null : (string) $sede;
    }

    public function shipmentDestinationSede(): ?string
    {
        $sede = $this->xml()?->RITIRO?->SPEDIZIONE?->SedeDestinazione;

        return $sede === null ? null : (string) $sede;
    }

    public function errorText(): ?string
    {
        $xml = $this->xml();

        if ($xml === null || ! isset($xml->TESTOERRORE)) {
            return null;
        }

        return (string) $xml->TESTOERRORE;
    }

    public function url(): string
    {
        return $this->url;
    }

    public function rawResponse(): string
    {
        return $this->rawResponse;
    }

    private function pickupEvent(string $date, string $time, string $place, string $state, string $code): TrackingEventData
    {
        $warning = false;

        try {
            $datetime = Carbon::createFromFormat('d/m/y H:i', $date.' '.$time);
        } catch (Exception $e) {
            $datetime = null;
            $warning = true;
        }

        return new TrackingEventData(
            datetime: $datetime,
            subsidiary: $place,
            code: $code,
            state: $state,
            warning: $warning,
        );
    }

    /**
     * @param  array<string, mixed>  $events
     */
    private function scalar(array $events, string $key): string
    {
        $value = $events[$key] ?? '';

        return is_array($value) ? '' : (string) $value;
    }

    private function xml(): ?SimpleXMLElement
    {
        if (strlen($this->rawResponse) === 0) {
            return null;
        }

        $xml = @simplexml_load_string($this->rawResponse, null, LIBXML_NOCDATA);

        return $xml === false ? null : $xml;
    }
}
